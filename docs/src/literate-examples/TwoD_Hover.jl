# ## Introduction
#
# All the bodies so far have been stationary. This example moves one, which is where WaterLily's
# implicit geometry earns its keep: the surface never has to be re-meshed, re-paneled or
# re-connected, because there is no mesh: moving the body means changing the `map` that the
# distance function is composed with.
#
# The setup is a flat plate that heaves from side to side while pitching, in fluid that is
# otherwise at rest, the two-dimensional cartoon of a hovering insect wing. There is no free
# stream at all: the simulation's boundary velocity is `(0,0)`, and every bit of fluid motion in
# the figure is generated by the body.
#
# Three new things appear:
#
#  - the **`map`** is a function of time, so the body moves. Its *velocity* is never written
#    down: [`AutoBody`](@ref) differentiates the map with respect to `t` to get it, which means
#    the kinematics and the body velocity can never disagree.
#  - **`remeasure=true`** (the default) tells [`sim_step!`](@ref) to re-measure the geometry each
#    step. For a stationary body that work is wasted, which is why every previous example passed
#    `remeasure=false`; for a moving one it is mandatory.
#  - **`ϵ`**, the width of the immersion kernel in cells. A thin body needs a thickness of at
#    least a couple of cells to be watertight, so the plate's half-thickness is tied to `ϵ`.
#
# ## Commented program
#
#md # The full program, without comments, can be found in the next
#md # [section](@ref TwoD_Hover-plain-program).

using WaterLily, StaticArrays, Plots

# ### A moving, rotating body
#
# The geometry is written once, in the body's own frame, as the distance to a line segment of
# length `L` lying on the ``y``-axis: clamp the point to the segment, take the distance to it,
# and offset by the half thickness. That expression knows nothing about where the plate is or
# what it is doing.
#
# The motion lives entirely in `map`, which transforms a *domain* point into the *body* frame,
# so it applies the inverse of the motion: subtract the (moving) body origin, then rotate by
# ``-\alpha``. Here the plate heaves sinusoidally in ``x`` and pitches with the same frequency,
# giving the figure-of-eight stroke of a hovering wing.

function hover(L = 2^5; Re = 250, U = 1, amp = π / 4, ϵ = 0.5, thk = 2ϵ + √2, mem = Array)
    ## distance to a line segment of length L, in the body frame
    function sdf(x, t)
        y = x .- SA[0, clamp(x[2], -L / 2, L / 2)]
        √sum(abs2, y) - thk / 2
    end
    ## heaving and pitching motion, mapping domain → body frame
    function map(x, t)
        α = amp * cos(t * U / L)
        R = SA[cos(α) sin(α); -sin(α) cos(α)]
        R * (x - SA[3L - L * sin(t * U / L), 4L])
    end
    Simulation((6L, 6L), (0, 0), L; U, ν = U * L / Re, body = AutoBody(sdf, map), ϵ, mem)
end

sim = hover();

# Start a quarter period in, so that the first frame is not the singular instant where the
# plate is instantaneously at rest at the top of its stroke.

sim_step!(sim, π)

# The body velocity that `AutoBody` derived from the map is stored in `sim.flow.V` after each
# measurement. Looking at it is the quickest check that a new set of kinematics is doing what
# you intended:

R = inside(sim.flow.p)
flood(sim.flow.V[R, 1]; clims = (-1, 1), cfill = :seismic, legend = false,
    title = "body velocity Vx/U")
body_plot!(sim)

# Note that it is non-zero only in a narrow band around the surface: the body velocity is only
# ever needed where the immersion kernel is active, so WaterLily does not bother filling it
# elsewhere.
#
# ### Running it
#
# The only change to the time loop is that `remeasure` is left at its default `true`, so the
# geometry and its velocity are re-measured at every step as the plate moves.

anim = @animate for tᵢ in range(π, π + 10; step = 0.1)
    sim_step!(sim, tᵢ)
    @inside sim.flow.σ[I] = WaterLily.curl(3, I, sim.flow.u) * sim.L / sim.U
    @inside sim.flow.σ[I] = ifelse(abs(sim.flow.σ[I]) < 0.001, 0.0f0, sim.flow.σ[I])
    flood(sim.flow.σ[R]; clims = (-5, 5), cfill = :seismic, legend = false, border = :none)
    body_plot!(sim)
end
gif(anim, "TwoD_Hover.gif", fps = 24)
nothing #hide

# Each stroke reversal leaves a vortex pair behind, and the pairs induce a downward jet, the
# momentum flux that holds a hovering animal up. Changing `amp` changes the pitch amplitude and
# with it the direction of the jet, which is the knob a real insect uses to steer.
#
# Because the map is differentiated rather than hand-coded, you can replace it with any
# kinematics you can write as a function of `t`: a prescribed flapping law measured from video,
# a rotation about a point that itself translates, or a deforming body whose map depends on both
# `x` and `t` (that is how a swimming fish is done).

